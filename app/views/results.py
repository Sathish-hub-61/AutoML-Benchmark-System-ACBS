"""Results page — recommendation card + 5 analysis tabs."""
from __future__ import annotations

import pandas as pd
import streamlit as st

from acbs.reporting.charts import confusion_matrix_heatmap, roc_curves
from api_client import ApiError, advisor, raw_results, recommendation, rerank
from components.charts_view import (
    framework_internals,
    overview_charts,
    radar_chart,
    sensitivity_chart,
    time_cost_charts,
)
from components.metrics_table import render_metrics_table
from components.recommendation_card import recommendation_card


def render() -> None:
    st.header("📈 Results")

    exp_id_default = int(st.session_state.get("experiment_id") or 1)
    exp_id = st.number_input("Experiment ID", min_value=1, value=exp_id_default, key="res_exp_id")

    try:
        rec = recommendation(int(exp_id))
    except ApiError as exc:
        st.info("Run a benchmark first, or check the experiment ID.")
        st.caption(str(exc))
        return

    # ── Recommendation card ─────────────────────────────────────────────────
    recommendation_card(rec)

    # ── AI advisor (Respan gateway; optional) ───────────────────────────────
    with st.expander("🧠 Ask the Advisor", expanded=False):
        question = st.text_input(
            "Question (optional)",
            key="res_advisor_q",
            placeholder="Explain this recommendation",
        )
        if st.button("Explain with the advisor", key="res_advisor_btn"):
            try:
                answer = advisor(int(exp_id), question or None)
                st.session_state.res_advisor_answer = answer
            except ApiError as exc:
                st.session_state.res_advisor_answer = None
                st.info("The AI advisor is unavailable; the explanation above still applies.")
                st.caption(str(exc))
        answer = st.session_state.get("res_advisor_answer")
        if answer:
            st.markdown(answer["narrative"])
            st.caption(f"Generated by {answer.get('model')} through the Respan gateway.")

    # Rerank sidebar
    with st.sidebar:
        st.markdown("---")
        st.subheader("🔁 Live Rerank")
        rr_preset = st.selectbox(
            "Priority preset",
            ["balanced", "max_accuracy", "fast_inference", "interpretable", "imbalance_safe"],
            key="res_rr_preset",
        )
        if st.button("Apply new priorities", key="res_rr_btn"):
            try:
                rec = rerank(int(exp_id), {"preset": rr_preset})
                st.session_state.last_rerank = rec
                st.rerun()
            except ApiError as exc:
                st.error(str(exc))

    # ── Build DataFrame ─────────────────────────────────────────────────────
    score_table = rec.get("score_table") or []
    df = pd.DataFrame(score_table)

    # Full result payload (per-model y_true / y_pred / y_proba / classes)
    try:
        result_payload = raw_results(int(exp_id))
    except ApiError:
        result_payload = {"models": []}
    models = result_payload.get("models", []) or []
    classes = result_payload.get("classes", [])

    # ── Tabs ────────────────────────────────────────────────────────────────
    tab_names = [
        "📊 Overview",
        "🕸 Radar",
        "⏱ Time & Cost",
        "📋 Leaderboard",
        "🎚 Sensitivity",
        "🔬 Framework Internals",
        "🎯 Diagnostics",
    ]
    tabs = st.tabs(tab_names)

    with tabs[0]:
        overview_charts(df)

    with tabs[1]:
        top_n = st.slider("Top-N models", 3, min(10, max(3, len(df))), min(6, len(df)), key="res_radar_n")
        radar_chart(df, top_n=top_n)

    with tabs[2]:
        time_cost_charts(df)

    with tabs[3]:
        render_metrics_table(df)

    with tabs[4]:
        sensitivity_chart(score_table)

    with tabs[5]:
        framework_internals(df)

    with tabs[6]:
        _diagnostics_tab(models, classes)


def _diagnostics_tab(models: list[dict], classes: list[str]) -> None:
    """Per-model confusion matrix and ROC curves from stored predictions."""
    st.header("🎯 Diagnostics")
    st.caption("Confusion matrix and ROC curve computed from each model's stored test predictions.")

    if not models:
        st.info("No model predictions available for diagnostics.")
        return

    ok_models = [m for m in models if m.get("status") == "ok" and m.get("y_pred")]
    if not ok_models:
        st.info("No completed models with stored predictions.")
        return

    model_names = [m["model_name"] for m in ok_models]
    chosen = st.selectbox("Model", model_names, key="diag_model")
    model = next(m for m in ok_models if m["model_name"] == chosen)

    y_true = model.get("y_true") or []
    y_pred = model.get("y_pred") or []
    y_proba = model.get("y_proba")
    labels = classes or list(range(len(set(y_true) | set(y_pred))))

    c1, c2 = st.columns(2)
    with c1:
        norm = st.selectbox(
            "Confusion matrix normalization",
            ["none", "true", "pred", "all"],
            index=0,
            key="diag_norm",
        )
        fig_cm = confusion_matrix_heatmap(
            y_true, y_pred, labels=labels, normalize=None if norm == "none" else norm
        )
        st.plotly_chart(fig_cm, width="stretch")
        tm = model.get("test_metrics") or {}
        st.markdown("### Test metrics")
        metric_cols = st.columns(4)
        for i, (k, v) in enumerate(
            {
                "accuracy": tm.get("accuracy"),
                "f1_macro": tm.get("f1_macro"),
                "precision_macro": tm.get("precision_macro"),
                "recall_macro": tm.get("recall_macro"),
                "roc_auc": tm.get("roc_auc"),
            }.items()
        ):
            with metric_cols[i % 4]:
                st.metric(k, f"{v:.4f}" if isinstance(v, (int, float)) else "—")

    with c2:
        if y_proba:
            fig_roc = roc_curves(y_true, y_proba)
            st.plotly_chart(fig_roc, width="stretch")
        else:
            st.info("No probability scores stored for this model (ROC unavailable).")
